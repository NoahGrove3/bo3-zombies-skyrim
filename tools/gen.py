"""Generate src/Generated.h from the sheets: one constexpr struct per row. Run preflight first."""
import json, pathlib, sys
root = pathlib.Path(__file__).parent.parent
S = {json.load(open(p))['sheet']: json.load(open(p)) for p in sorted((root / 'sheets').glob('*.json'))}
def row(s, i): return next(r for r in S[s]['rows'] if r['id'] == i)
def cs(x): return json.dumps(x)
def hexid(x): return int(x, 16)
out = ['// GENERATED by tools/gen.py from sheets/*.json. Edit the sheets, not this file.', '#pragma once', '#include <array>', '#include <cstdint>', '#include <string_view>', '', 'namespace bo3z::gen', '{']
out.append('\tstruct FormRef { std::string_view plugin; std::uint32_t localId; std::string_view editorId; };')
# rounds
r = row('rounds', 'night_rounds')
out.append('\tstruct Rounds {\n\t\tfloat nightStartHour, nightEndHour, breakSeconds, firstBreakSeconds; int maxAlive, aiMaxBase, aiPerPlayer;\n\t\tstd::array<float, 5> earlyRoundScale; int hpStart, hpLinearPerRound, hpLinearUntil; float hpMultAfter, hpScale;\n\t\tfloat spawnDelayStart, spawnDelayDecay, spawnDelayMin; int specialEveryRounds, specialFirstRound;\n\t\tstd::array<float, 2> spawnRingExterior, spawnRingInterior; float spawnHeightOffset; int maxCorpses; };')
out.append(f'\tinline constexpr Rounds kRounds{{ {r["nightStartHour"]}f, {r["nightEndHour"]}f, {r["breakSeconds"]}f, {r["firstBreakSeconds"]}f, {r["maxAlive"]}, {r["aiMaxBase"]}, {r["aiPerPlayer"]},\n\t\t{{ {", ".join(str(x)+"f" for x in r["earlyRoundScale"])} }}, {r["hpStart"]}, {r["hpLinearPerRound"]}, {r["hpLinearUntil"]}, {r["hpMultAfter"]}f, {r["hpScale"]}f,\n\t\t{r["spawnDelayStart"]}f, {r["spawnDelayDecay"]}f, {r["spawnDelayMin"]}f, {r["specialEveryRounds"]}, {r["specialFirstRound"]},\n\t\t{{ {r["spawnRingExterior"][0]}.f, {r["spawnRingExterior"][1]}.f }}, {{ {r["spawnRingInterior"][0]}.f, {r["spawnRingInterior"][1]}.f }}, {r["spawnHeightOffset"]}.f, {r["maxCorpses"]} }};')
assert r['dawn'] == 'crumble' and r['unfinishedRound'] == 'resume'
q = row('quests', r['pauseUntilQuest'].split(':')[1])
out.append(f'\tinline constexpr FormRef kIntroQuest{{ {cs(q["plugin"])}, 0x{hexid(q["localId"]):06X}, {cs(q["editorId"])} }};')
# enemies
out.append('\tstruct Enemy { std::string_view id, label; FormRef form; bool isLeveledList; int minRound, weight; bool specialRound; std::string_view headNode; bool forceCombat; };')
en = S['enemies']['rows']
out.append(f'\tinline constexpr std::array<Enemy, {len(en)}> kEnemies{{ {{')
for e in en:
    out.append(f'\t\tEnemy{{ {cs(e["id"])}, {cs(e["label"])}, {{ {cs(e["plugin"])}, 0x{hexid(e["localId"]):06X}, {cs(e["editorId"])} }}, {str(e["recordType"]=="LVLN").lower()}, {e["minRound"]}, {e["weight"]}, {str(e["specialRound"]).lower()}, {cs(e["headNode"])}, {str(e["forceCombat"]).lower()} }},')
out.append('\t} };')
# sounds
out.append('\tenum class Sound : int {')
snd = S['sounds']['rows']
for i, s in enumerate(snd): out.append(f'\t\t{s["id"]} = {i},')
out.append('\t};')
out.append(f'\tinline constexpr std::array<FormRef, {len(snd)}> kSounds{{ {{')
for s in snd: out.append(f'\t\tFormRef{{ {cs(s["plugin"])}, 0x{hexid(s["localId"]):06X}, {cs(s["editorId"])} }},')
out.append('\t} };')
# weapons
out.append('\tstruct Gun { std::string_view id, label; float damage, headMult; int clip, reserve, fireDelayMs, reloadMs; float range, hitRadius, headRadius; Sound fire, reload, empty; bool startOwned; };')
ws = S['weapons']['rows']
for w in ws:
    sid = lambda v: 'Sound::' + v.split(':')[1]
    out.append(f'\tinline constexpr Gun kGun_{w["id"]}{{ {cs(w["id"])}, {cs(w["label"])}, {w["damage"]}.f, {w["headMult"]}f, {w["clip"]}, {w["reserve"]}, {w["fireDelayMs"]}, {w["reloadMs"]}, {w["range"]}.f, {w["hitRadius"]}.f, {w["headRadius"]}.f, {sid(w["fireSound"])}, {sid(w["reloadSound"])}, {sid(w["emptySound"])}, {str(w["startOwned"]).lower()} }};')
# economy
for e in S['economy']['rows']: out.append(f'\tinline constexpr int kPoints_{e["id"]} = {e["points"]};  // {e["event"]}')
# input
for i in S['input']['rows']: out.append(f'\tinline constexpr std::uint32_t kKey_{i["id"]} = {i["code"]};  // {i["device"]}: {i["action"]}')
out.append(f'\tinline constexpr bool kFireIsMouse = {str(row("input","fire")["device"]=="mouse").lower()};')
# persistence
for p in S['persistence']['rows']: out.append(f'\tinline constexpr int kAV_{p["id"]} = /*{p["actorValue"]}*/ {68 + int(p["actorValue"][-2:]) - 1};')
# hud
out.append('\tstruct HudItem { std::string_view id; int anchor; float ox, oy, fontPx; std::uint32_t rgba; };')
anchors = {'bottom_left':0,'bottom_right':1,'center':2,'top_center':3}
for h in S['hud']['rows']:
    c = int(h['color'][1:], 16)
    out.append(f'\tinline constexpr HudItem kHud_{h["id"]}{{ {cs(h["id"])}, {anchors[h["anchor"]]}, {h["offset"][0]}.f, {h["offset"][1]}.f, {h["fontPx"]}.f, 0x{(c<<8)|0xFF:08X} }};')
out.append('}')
(root / 'src').mkdir(exist_ok=True)
(root / 'src/Generated.h').write_text('\n'.join(out) + '\n')
print('wrote src/Generated.h', len(out), 'lines')
