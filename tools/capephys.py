"""capephys.py <grid.txt> <out.xml> <cape shape name>
(Noah: "make the cape flow as I'm moving around ... similar physics to the hair") the FSMP (HDT-SMP) physics for a cape
reweighted by tools/modelconv/capephys.cpp: its grid of CAPE_C<c>_R<r> bones (read from that tool's printout), each
column a chain hanging from the upper back, every bone tied to its neighbours across and diagonally so the cloth folds and
sways as one piece; the cape slides off hidden collision proxies on the hips, legs, arms and hands.
The grid starts just under the shoulders (Noah: "animated above the waist, all the way up until about shoulder height").
Fabric: a heavy wool cape (it moves with you and settles; it doesn't flutter like silk)."""
import re, sys

grid = {}
skin = []
for line in open(sys.argv[1]):
    if line.startswith('skinbone '): skin.append(line[9:].rstrip('\n'))
    m = re.match(r'bone CAPE_C(\d+)_R(\d+) ', line)
    if m: grid[(int(m[1]), int(m[2]))] = True
C = max(c for c, r in grid) + 1
R = max(r for c, r in grid) + 1
name = lambda c, r: f'CAPE_C{c}_R{r}'
shape = sys.argv[3]

def v3(tag, x, y=None, z=None):
    y = x if y is None else y; z = x if z is None else z
    return f'<{tag} x="{x}" y="{y}" z="{z}"/>'

o = ['<?xml version="1.0" encoding="UTF-8"?>',
     f'<!-- The Curse of Alduin - {shape}: a heavy cape on FSMP bone physics, {C} columns x {R} rows (generated by tools/capephys.py) -->',
     '<system xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="definitions.xsd">',
     '  <bone-default><mass>0</mass><inertia x="0" y="0" z="0"/><centerOfMassTransform><basis x="0" y="0" z="0" w="1"/><origin x="0" y="0" z="0"/></centerOfMassTransform>'
     '<linearDamping>0</linearDamping><angularDamping>0</angularDamping><friction>0.5</friction><rollingFriction>0</rollingFriction><restitution>0</restitution><margin-multiplier>1</margin-multiplier></bone-default>']
for b in ['NPC Spine2 [Spn2]', 'NPC Spine1 [Spn1]', 'NPC Pelvis [Pelv]', 'NPC L Thigh [LThg]', 'NPC R Thigh [RThg]', 'NPC L Calf [LClf]', 'NPC R Calf [RClf]',
          'NPC L Foot [Lft ]', 'NPC R Foot [Rft ]', 'NPC L Forearm [LLar]', 'NPC R Forearm [RLar]', 'NPC L Hand [LHnd]', 'NPC R Hand [RHnd]'] + \
        [b for b in skin if b not in ('NPC Spine2 [Spn2]', 'NPC Spine1 [Spn1]')]:  # (Noah: "a dark sheet above my head") every bone the cape is skinned to: SMP takes over the shape's skinning, and an undeclared bone (the collar's neck, head, clavicles, arms) threw its vertices up
    o.append(f'  <bone name="{b}"/>')
# the cloth: heavier at the top, the hem calmed by damping
o.append('  <bone-default><mass>1.8</mass><inertia x="32" y="32" z="14"/><centerOfMassTransform><basis x="0" y="0" z="0" w="1"/><origin x="0" y="0" z="-6"/></centerOfMassTransform>'
         '<linearDamping>0.65</linearDamping><angularDamping>0.88</angularDamping><friction>0.15</friction><rollingFriction>0</rollingFriction><restitution>0</restitution><margin-multiplier>1</margin-multiplier></bone-default>')
for r in range(R):
    for c in range(C):
        extra = '<linearDamping>0.75</linearDamping><angularDamping>0.92</angularDamping>' if r >= R - 2 else ''
        o.append(f'  <bone name="{name(c, r)}"><mass>{2.2 - 0.12 * r:.2f}</mass>{extra}</bone>')
# hanging joints: each bone from the one above (row 0 from the upper back). (Noah: "it should just flare backwards when I'm
# running straight, or to the side a little, depending on which direction I'm moving. It should be subtle, not flying all
# over the place") small swings, held stiff: x (back/forward) a tenth of a radian a joint - the hem can lift ~35 degrees
# at a sprint - y (sideways) a third of that, almost no twist; the top row, at the shoulder blades, barely moves
for r in range(R):
    lim = (0.10 + 0.01 * r, 0.035 + 0.005 * r, 0.02) if r else (0.04, 0.02, 0.02)
    stiff = (140 - 12 * r, 160 - 12 * r, 180) if r else (200, 200, 200)
    o.append('  <generic-constraint-default>')
    o += ['    <frameInA><basis x="0" y="0" z="0" w="1"/><origin x="0" y="0" z="0"/></frameInA>', '    <useLinearReferenceFrameA>false</useLinearReferenceFrameA>',
          '    ' + v3('linearLowerLimit', 0), '    ' + v3('linearUpperLimit', 0),
          '    ' + v3('angularLowerLimit', -lim[0], -lim[1], -lim[2]), '    ' + v3('angularUpperLimit', lim[0], lim[1], lim[2]),
          '    ' + v3('linearStiffness', 0), '    ' + v3('angularStiffness', *stiff), '    ' + v3('linearDamping', 0), '    ' + v3('angularDamping', 1.5, 1.5, 1.6),
          '    ' + v3('linearEquilibrium', 0), '    ' + v3('angularEquilibrium', 0), '    ' + v3('linearBounce', 0), '    ' + v3('angularBounce', 0)]
    o.append('  </generic-constraint-default>')
    for c in range(C):
        o.append(f'  <generic-constraint bodyA="{name(c, r)}" bodyB="{name(c, r - 1) if r else "NPC Spine2 [Spn2]"}"/>')
# across and diagonally: the cloth holds together (no columns sliding past each other)
o.append('  <stiffspring-constraint-default><minDistanceFactor>0.95</minDistanceFactor><maxDistanceFactor>1.02</maxDistanceFactor><stiffness>90</stiffness><damping>0.9</damping><equilibrium>0.5</equilibrium></stiffspring-constraint-default>')
for r in range(R):
    for c in range(C - 1):
        o.append(f'  <stiffspring-constraint bodyA="{name(c, r)}" bodyB="{name(c + 1, r)}"/>')
o.append('  <stiffspring-constraint-default><minDistanceFactor>0.85</minDistanceFactor><maxDistanceFactor>1.06</maxDistanceFactor><stiffness>45</stiffness><damping>0.9</damping><equilibrium>0.714</equilibrium></stiffspring-constraint-default>')
for r in range(1, R):
    for c in range(C - 1):
        o.append(f'  <stiffspring-constraint bodyA="{name(c, r)}" bodyB="{name(c + 1, r - 1)}"/>')
        o.append(f'  <stiffspring-constraint bodyA="{name(c + 1, r)}" bodyB="{name(c, r - 1)}"/>')
# collision: the cape against the body's hidden proxies (margin = their radius)
o += [f'  <per-vertex-shape name="{shape}"><margin>1.0</margin><shared>private</shared><tag>ca_cape</tag><can-collide-with-tag>ca_body</can-collide-with-tag></per-vertex-shape>']
# (Noah: "it was deforming my character") this cape hangs close to the back: the cloak mod's proxies, sized for its fuller
# cloaks, sat inside it and shoved it out of shape. Smaller here: they reach just short of where the cape hangs
for s, m in (('CC_BodyCollision', 4.0), ('CC_ColThighs', 5.5), ('CC_ColCalves', 4.0), ('CC_ColFeet', 3.5), ('CC_ColForearms', 2.5), ('CC_ColHands', 2.2)):
    o.append(f'  <per-vertex-shape name="{s}"><margin>{m}</margin><shared>private</shared><tag>ca_body</tag><can-collide-with-tag>ca_cape</can-collide-with-tag></per-vertex-shape>')
o.append('</system>')
open(sys.argv[2], 'w', newline='\r\n').write('\n'.join(o) + '\n')
print(f'{C}x{R} cape physics -> {sys.argv[2]}')
