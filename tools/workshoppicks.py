"""Noah's final workshop picks for the code (Nov 26: "all my picks at once" for the in-game test): the sounds he chose for each
ability (each at 20% - "the weapon sound effects should be kind of a background noise"), Skyrim's own weapon sounds that go to
20% for every weapon in the game, his hit feel, hit markers, deaths, trial sounds and the big-night settings.

    python tools/workshoppicks.py     -> src/WorkshopPicks.h  (reads docs/workshop/final_picks.json, sound_picks.json, build/sound/sndr.json)
"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import realfx

W = ROOT / 'docs' / 'workshop'
FINAL = json.loads((W / 'final_picks.json').read_text())
SP = json.loads((W / 'sound_picks.json').read_text())
SN = json.loads((ROOT / 'build' / 'sound' / 'sndr.json').read_text())
BY = {s['ed']: s for s in SN['sndr']}
TRIALS = json.loads((W / 'trials.json').read_text())
SHEET = json.loads((ROOT / 'sheets' / 'sounds.json').read_text())
COA = {f.split('\\')[-1][:-4]: r['id'] for r in SHEET['rows'] for f in r['files']}
VOL = SP['vol'] / 100.0


def snd(ref, gain=1.0, delay=0.0):
    """one sound for the code: Skyrim's (plugin, its own id) or ours (gen::Sound)"""
    if ref.startswith('coa:'):
        return f'{{ nullptr, 0, {gain:.3f}f, {delay:.2f}f, static_cast<int>(gen::Sound::{COA[ref[4:]]}) }}'
    s = BY[ref]
    return f'{{ "{s["src"]}", 0x{s["fid"]:06X}, {gain:.3f}f, {delay:.2f}f, -1 }}'   # {ref}


def layers(slot):
    out = [(r, g, d) for r, g, d in slot['snd']]
    return out


def main():
    L = ['#pragma once', '// Generated by tools/workshoppicks.py from Noah\'s workshop picks (docs/workshop/final_picks.json, sound_picks.json) - do not edit.',
         '// (Noah, 2026-11-26: "all my picks at once" for the in-game test)', '', 'namespace coa::Picks', '{',
         '\tstruct Snd { const char* plugin; std::uint32_t id; float gain, delay; int ours; };   // (ours: a gen::Sound, -1 when Skyrim\'s)',
         '\tstruct CardSnd { const char* card; const char* slot; Snd s[3]; int n; };',
         f'\tinline constexpr float kWeaponVol = {VOL:.2f}f;   // every weapon and ability sound, the flasks too ("kind of a background noise")', '']
    # each ability's picked sound, where he chose one of its options (what plays now stays, at 20%)
    rows = []
    for card, slots in SP['abilities'].items():
        for sid, sl in slots.items():
            if not sl.get('set') or sl.get('flask') or sl['opt'] == 'a1' or not sl['snd']: continue
            ss = [snd(r, g * VOL, d) for r, g, d in sl['snd']][:3]
            rows.append(f'\t\t{{ "{card}", "{sid}", {{ {", ".join(ss)} }}, {len(ss)} }},')
    L += ['\tinline constexpr CardSnd kCardSnd[] = {'] + rows + ['\t};']
    # the owners (src/Gun.cpp FxScope) and the card each speaks for
    own = [(a['owner'], a['card']) for a in realfx.ABIL]
    L += ['\tinline constexpr std::pair<const char*, const char*> kOwnerCard[] = {'] + [f'\t\t{{ "{o}", "{c}" }},' for o, c in own] + ['\t};']
    # Skyrim's own weapon sounds (draw, sheathe, swing, impact) at 20% for every weapon in the game
    quiet = sorted({(s['src'], s['fid'], s['ed']) for s in SN['sndr'] if s['files'] and s['src'] in ('Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'Dragonborn.esm')
                    and s['ed'].startswith('WPN') and any(k in s['ed'] for k in ('Swing', 'Impact', 'Draw', 'Sheathe'))})
    L += [f'\t// Skyrim\'s own weapon sounds ({len(quiet)}: every WPN draw, sheathe, swing and impact), 20% for every weapon',
          '\tinline constexpr std::pair<const char*, std::uint32_t> kQuietSndr[] = {'] + [f'\t\t{{ "{p}", 0x{f:06X} }},   // {e}' for p, f, e in quiet] + ['\t};']
    # hit feel: hit-stop (ms) on a hit and a power attack, shake (%) on a power attack, by weight (0 light, 1 medium, 2 heavy)
    fe = FINAL['feel']
    def fv(c, k): return fe.get(c, {}).get(k, 0)
    L += ['\t// hit feel by weight - light (daggers, claws), medium (swords, maces, rapiers), heavy (two-handed): stop on a hit, on a heavy (ms); shake on a heavy (%)',
          '\tinline constexpr float kStopL[3] = { ' + ', '.join(f'{fv(c, "stopL")}.0f' for c in ('light', 'medium', 'heavy')) + ' };',
          '\tinline constexpr float kStopH[3] = { ' + ', '.join(f'{fv(c, "stopH")}.0f' for c in ('light', 'medium', 'heavy')) + ' };',
          '\tinline constexpr float kShakeH[3] = { ' + ', '.join(f'{fv(c, "shakeH")}.0f' for c in ('light', 'medium', 'heavy')) + ' };']
    mk = lambda k: fe.get('mark_' + k, {}).get('choice', 'keep')
    L += [f'\tinline constexpr bool kHitMarks = {"false" if mk("mark") == "off" else "true"};   // the crosshair\'s hit and kill marks and their ticks',
          f'\tinline constexpr bool kHeadMarks = {"false" if mk("head") == "off" else "true"};  // a headshot\'s tick and white flash',
          f'\tinline constexpr bool kLastKillSlow = {"true" if mk("last") == "slow" else "false"};  // the night\'s last kill in slow motion',
          f'\tinline constexpr bool kHeavyThrows = {"true" if FINAL["deaths"].get("plain", {}).get("opt") == "a2" else "false"};  // a power attack\'s kill throws the body']
    # trial sounds he changed: event -> its sound
    tr = FINAL['trials']
    evs = []
    for ev in TRIALS['common'] + [e for t in TRIALS['trials'] for e in t['events']]:
        tid = 'common' if ev in TRIALS['common'] else next(t['id'] for t in TRIALS['trials'] if ev in t['events'])
        pick = tr.get(tid, {}).get('snd', {}).get(ev['id'], 'a1')
        if pick == 'a1': continue
        o = next(x for x in ev['opts'] if x['id'] == pick)
        ss = [snd(r) for r in o['snd']][:3]
        evs.append(f'\t\t{{ "{ev["id"]}", "trial", {{ {", ".join(ss)} }}, {len(ss)} }},   // {o["name"]}')
    L += ['\tinline constexpr CardSnd kTrialSnd[] = {'] + evs + ['\t};']
    ec = tr.get('echo', {})
    L += [f'\tinline constexpr float kHoldFrom = {float(ec.get("radius", 1100)):.1f}f;   // Hold the Light: the ring\'s start',
          f'\tinline constexpr const char* kHoldPal = "{"blue" if ec.get("ring", "").lower() in ("#007bff",) else ""}";   // its ring\'s colour (one of our ramps; empty: as built)']
    pf = FINAL['perf']
    L += [f'\tinline constexpr bool kFxAutoDetail = {"true" if pf.get("detail", {}).get("choice") == "auto" else "false"};   // fewer particles past 30 of the dead near you',
          f'\tinline constexpr bool kFxBigLightsOnly = {"true" if pf.get("lights", {}).get("choice") == "big" else "false"};   // only big effects cast light on a big night',
          '}', '']
    (ROOT / 'src' / 'WorkshopPicks.h').write_text('\n'.join(L))
    print(len(rows), 'card sounds,', len(quiet), 'quiet Skyrim sounds,', len(evs), 'trial sounds')


if __name__ == '__main__':
    main()
