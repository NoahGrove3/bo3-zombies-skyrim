"""The Curse of Alduin's creatures in The Dragonborn's Bestiary: data/CurseOfAlduin_Bestiary_DISTR.ini (a SPID file that
files each enemy row under the Bestiary's nearest existing entry). Rows already covered by the Bestiary's own rules
(Diverse Dragons, the Bone Colossus, goblins, ogres) are left out.  python3 tools/bestiary.py"""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
M = {'Draugr': ['zombie', 'hollow2', 'hollow3', 'necro', 'hexer_rime', 'hexer_storm', 'king', 'knight', 'lich', 'bloater'],
     'Skeleton': ['ash1', 'ash2', 'marksman', 'skeleton', 'reaper', 'runner', 'shadow'],
     'Ghost': ['wailer'], 'Death Hound': ['death_hound'], 'Giant': ['brute', 'boss3', 'hf_ettin'], 'Frost Giant': ['mb_ice_titan'],
     'Troll': ['hf_troll'], 'Minotaur': ['hf_minotaur'], 'Minotaur Lord': ['mb_minotaur_lord'], 'Scamp': ['hf_imp_fire', 'hf_imp_shock', 'mb_vile_imp']}
e = {r['id']: r for r in json.load(open(ROOT / 'sheets' / 'enemies.json'))['rows']}
out = ["; The Curse of Alduin: its night's creatures in The Dragonborn's Bestiary (SPID). Each is filed under the Bestiary's",
       "; nearest entry - the Bestiary has no pages of its own for the Curse's unique ones (the Elk-Crowned, harpies, oozes, centipedes).",
       "; generated by tools/bestiary.py from sheets/enemies.json"]
for k, ids in M.items():
    out.append(f"Keyword = Bestiary{k}|{','.join(e[i]['editorId'] for i in ids)}|NONE|NONE|NONE|NONE|NONE")
(ROOT / 'data' / 'CurseOfAlduin_Bestiary_DISTR.ini').write_text('\n'.join(out) + '\n', newline='\r\n')
print('wrote data/CurseOfAlduin_Bestiary_DISTR.ini')
