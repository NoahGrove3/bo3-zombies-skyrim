"""Write docs/AUDIO_MAP.md (Spec 12.12: inventory, assignment map, gaps) from sheets/sfx.json and sheets/sounds.json.
    python tools/audiomap.py"""
import json, pathlib, collections
ROOT = pathlib.Path(__file__).resolve().parent.parent
sfx = json.load(open(ROOT / 'sheets/sfx.json'))
snd = json.load(open(ROOT / 'sheets/sounds.json'))
used = collections.defaultdict(list)
for r in snd['rows']:
    for f in r.get('files', []):
        used[pathlib.PurePath(f.replace('\\', '/')).stem].append(r['id'])
music = {'mus_menu': 'main menu (sMainMenuMusic)', 'mus_boss': 'Grimmvar (MUSC UN_MUSBoss)', 'mus_freed': 'a city freed (MUSC UN_MUSFreed)',
         'mus_intro': 'the intro film (MUSC UN_MUSIntro)'}
L = ['# The Curse of Alduin: audio inventory and assignment map', '',
     'Generated by `tools/audiomap.py` from `sheets/sfx.json` (clips cut from the supplied libraries by `tools/sfx.py`) and '
     '`sheets/sounds.json` (every sound the mod plays, built by `tools/soundmap.py`). No Skyrim sound effects are referenced.', '',
     f"## 1. Supplied files ({len(sfx['sources'])})", '', '| Alias | File | Clips cut from it |', '|---|---|---|']
by_src = collections.defaultdict(list)
for c in sfx['rows']:
    by_src[c['src']].append(c['id'])
for a, f in sfx['sources'].items():
    L.append(f"| {a} | {pathlib.PurePath(f).name} | {', '.join(by_src[a]) or '(not used: see section 4)'} |")
L += ['', '## 2. Clips and what plays them', '', '| Clip | From | Use | Played by |', '|---|---|---|---|']
for c in sfx['rows']:
    L.append(f"| {c['id']} | {c['src']} | {c.get('use', '')} | {music.get(c['id']) or ', '.join(sorted(set(used[c['id']]))) or '(unused)'} |")
L += ['', '## 3. Sounds (SNDR) and their clips', '', '| Sound | 2D/3D | Category | Loop | Pitch | Clips | Use |', '|---|---|---|---|---|---|---|']
for r in snd['rows']:
    clips = ', '.join(pathlib.PurePath(f.replace('\\', '/')).stem for f in r.get('files', []))
    L.append(f"| {r['id']} | {r['space']} | {r.get('cat', 'sfx')} | {'yes' if r.get('loop') else ''} | {r.get('shift', 0):+d}% | {clips} | {r.get('use', '')} |")
L += ['', '## 4. Gaps and notes',
      '- Footsteps: the undead step with the supplied footstep recordings on their own animation footfalls (walk and run sets per type); the races\' own steps are silenced by an empty footstep set on their skins.',
      '- Spell stages per spell (Spec 12.3): charging begins (`start_`), the hum while it gathers (`charge_`), full charge (`full_`), an early release (`fizzle_`), the quick cast (`cast_`), the signature release (`unleash_` plus `release_power`), the bolt in flight (`travel_`, on the projectile), the impact (`hit_`), the gathered burst (`boom_`) and lingering marks (`linger_`).',
      '- The libraries have one fire, one ice, one shock and one holy family; spells of the same element differ by take, engine pitch, layered clips and their own release and burst.',
      '- Unused supplied material is listed in section 1 as "not used".',
      '- Engine sounds that are not ours: the player\'s own footsteps and the world (water, wind, NPCs) stay Skyrim\'s; the mod adds nothing there.']
(ROOT / 'docs/AUDIO_MAP.md').write_text('\n'.join(L) + '\n')
print('wrote docs/AUDIO_MAP.md', len(L), 'lines')
